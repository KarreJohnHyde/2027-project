import { chromium } from "playwright-core";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const root = process.cwd();
const read = (file) => JSON.parse(readFileSync(file, "utf8").replace(/^\uFEFF/, ""));
const stack = read(path.join(root, ".cache/review-20261113/stack.json"));
if (stack.mode !== "qa") throw new Error("Isolated QA stack required");
const credentials = read(stack.credentials_file);
const proof = read(path.join(root, "artifacts/expansion-2026-11-13/imaging/qa-proof.json"));
const out = path.join(root, "artifacts/expansion-2026-11-13/imaging/browser"); mkdirSync(out, { recursive: true });
const result = { scope: "Original synthetic matched source-space temporal control; no clinical progression validation or model inference.", checks: [], page_errors: [], server_errors: [] };
const browser = await chromium.launch({ channel: "msedge", headless: true });
const context = await browser.newContext({ viewport: { width: 1500, height: 1100 } });
const page = await context.newPage(); page.setDefaultTimeout(30000);
page.on("pageerror", (error) => result.page_errors.push(String(error)));
page.on("response", (response) => { if (response.status() >= 500) result.server_errors.push({ status: response.status(), path: new URL(response.url()).pathname }); });
const check = (name, passed) => { result.checks.push({ name, passed: Boolean(passed) }); if (!passed) throw new Error(name); };
try {
  await page.goto(stack.web_url+"/account");
  await page.locator("#account-identifier").fill(credentials.username);
  await page.locator("#account-secret").fill(credentials.password);
  await page.getByRole("button", { name: "Open account", exact: true }).click();
  await page.getByRole("button", { name: "Sign out", exact: true }).waitFor();
  await page.evaluate((id) => localStorage.setItem("medtwin.selectedCase", String(id)), proof.case_id);
  await page.goto(stack.web_url+"/universal");
  await page.getByRole("tab", { name: "Spatial imaging", exact: true }).click();
  const panel = page.getByTestId("temporal-image-comparison");
  await panel.locator("summary").first().click();
  await panel.getByLabel("Temporal previous source", { exact: true }).selectOption(String(proof.upload_ids[0]));
  await panel.getByLabel("Temporal current source", { exact: true }).selectOption(String(proof.upload_ids[1]));
  await panel.getByLabel("Temporal previous anatomical region", { exact: true }).fill("synthetic phantom");
  await panel.getByLabel("Temporal current anatomical region", { exact: true }).fill("synthetic phantom");
  const prepare = panel.getByRole("button", { name: "Prepare matched comparison", exact: true });
  check("source correspondence attestations are required", await prepare.isDisabled());
  await panel.getByLabel("Same subject at both declared timepoints", { exact: true }).check();
  await panel.getByLabel("Matching anatomical region and acquisition coverage", { exact: true }).check();
  await panel.getByLabel("Comparable intensity protocol (actual encoded metadata must also qualify)", { exact: true }).check();
  await panel.getByLabel("Temporal alignment", { exact: true }).selectOption("shared_physical_space");
  check("shared physical space requires a separate alignment attestation", await prepare.isDisabled());
  await panel.getByLabel(/I explicitly attest pre-existing anatomical alignment/).check();
  await prepare.click();
  await panel.getByText("CANDIDATE_UNVALIDATED", { exact: false }).waitFor();
  await panel.getByRole("img", { name: "Matched checkerboard comparison plane", exact: true }).waitFor();
  check("matched previous/current/checkerboard planes render", await panel.getByRole("img").count() === 3);
  const response = page.waitForResponse((response) => response.url().includes("/temporal-comparisons/") && response.url().endsWith("/render") && response.request().postDataJSON()?.mode === "difference");
  await panel.getByLabel("Temporal comparison view", { exact: true }).selectOption("difference");
  const difference = await response;
  result.difference_metadata = JSON.parse(difference.headers()["x-medtwin-comparison"]);
  await panel.getByRole("img", { name: "Matched difference comparison plane", exact: true }).waitFor();
  check("actual UI raw intensity difference matches independently specified synthetic change", Math.abs(result.difference_metadata.statistics.mean_current_minus_previous-proof.expected_mean_change) < 1e-6);
  check("invalid pixels are explicitly excluded from change statistics", result.difference_metadata.statistics.invalid_pixels_excluded);
  check("comparison remains unvalidated and makes no clinical progression claim", result.difference_metadata.status === "CANDIDATE_UNVALIDATED" && !result.difference_metadata.clinical_progression_claim);
  await panel.getByText("Verified source identities", { exact: true }).click();
  check("both verified source hashes remain inspectable", (await panel.locator("pre").textContent()).includes(proof.request.previous.sha256) && (await panel.locator("pre").textContent()).includes(proof.request.current.sha256));
  await panel.scrollIntoViewIfNeeded(); await page.screenshot({ path: path.join(out, "matched-difference.png"), fullPage: false });
  await page.addScriptTag({ path: require.resolve("axe-core/axe.min.js") });
  const audit = async (width) => {
    const axe = await page.evaluate(async () => window.axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa"] } }));
    result.accessibility ??= [];
    result.accessibility.push({ viewport: width, passes: axe.passes.length, violations: axe.violations.map((violation) => ({ id: violation.id, impact: violation.impact, nodes: violation.nodes.map((node) => ({ target: node.target, summary: node.failureSummary })) })), incomplete: axe.incomplete.map((item) => ({ id: item.id, nodes: item.nodes.length })) });
    check(`expanded temporal comparison has no automated WCAG A/AA violations at${width}px`, axe.violations.length === 0);
  };
  await audit(1500);
  await panel.getByLabel("Temporal plane", { exact: true }).selectOption("sagittal");
  await panel.getByRole("img", { name: "Matched difference comparison plane", exact: true }).waitFor();
  check("slice plane changes stay synchronized across matched sources", await panel.getByRole("img").count() === 3);
  await panel.getByLabel("Temporal current anatomical region", { exact: true }).fill("heart");
  check("editing source correspondence invalidates the old comparison", await panel.getByText("CANDIDATE_UNVALIDATED", { exact: false }).count() === 0);
  await prepare.click();
  await panel.getByText("ANATOMICAL_REGION_MISMATCH", { exact: false }).waitFor();
  check("mismatched anatomy produces an explicit refusal", true);
  await page.setViewportSize({ width: 390, height: 844 });
  result.mobile = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth }));
  check("temporal controls fit a mobile viewport", result.mobile.width <= result.mobile.viewport);
  await audit(390);
  check("no uncaught page errors", result.page_errors.length === 0);
  check("no backend500 responses", result.server_errors.length === 0);
} catch (error) {
  result.failure = String(error); process.exitCode = 1;
  await page.screenshot({ path: path.join(out, "failure.png"), fullPage: false });
} finally {
  writeFileSync(path.join(out, "proof.json"), JSON.stringify(result, null, 2));
  await browser.close(); console.log(JSON.stringify(result));
}
