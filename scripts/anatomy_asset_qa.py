"""Joins the anatomy manifest with a browser walkthrough into docs/anatomy/ASSET_QA.md.

The manifest (public/anatomy/manifest.json, built by tools/asset-pipeline) carries the
static QA of every variant: source path and SHA-256, licence, glTF validator result,
mesh statistics, view types, derived tiers and registration status. The walkthrough
(tools/browser-qa/walkthrough.mjs) adds what the browser actually rendered. Also writes
assets/anatomy/asset_manifest.json, the directive's path, as a pointer to the canonical
manifest plus a per-variant summary.

  python scripts/anatomy_asset_qa.py --walkthrough %TEMP%/medtwin-qa/walkthrough-<stamp>/walkthrough.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "public" / "anatomy" / "manifest.json"


def number(value) -> str:
    return f"{int(value):,}" if value else "0"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--walkthrough", required=True, type=Path)
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    walk = json.loads(args.walkthrough.read_text(encoding="utf-8"))
    rendered = {item["variant"]: item for item in walk["sections"]["anatomy"]["variants"]}
    variants = manifest["variants"]

    rows, summary = [], []
    for system in manifest["systems"]:
        for variant_id in system["variants"]:
            variant = variants[variant_id]
            stats = variant.get("statistics", {})
            source = variant.get("source") or {}
            browser = rendered.get(variant_id)
            # Atlas references stream chunks from the shared atlas instead of per-variant tiers.
            tiers = variant.get("tiers") or {}
            tier = tiers.get("standard") or next(iter(tiers.values()), {})
            if stats.get("points"):
                geometry = f"{number(stats['points'])} points"
            elif stats.get("triangles"):
                geometry = f"{number(stats['triangles'])} tris"
            else:  # atlas references: chunks of the shared atlas, counted per structure
                geometry = f"{stats.get('structures', 0)} atlas structures"
            if browser is None:
                result = "NOT_RUN"
            elif browser["rendered"]:
                drawn = f"{number(browser['points'])} pts" if browser.get("points") else f"{number(browser['triangles'])} tris"
                result = f"RENDERED ({browser['draw_calls']} calls, {drawn}, σ {browser['pixel_stats']['luminance_std']:.0f}, {browser['seconds']:.1f} s)"
            else:
                result = f"NOT_RENDERED ({browser.get('error') or 'no frame statistics'})"
            rows.append(f"| {system['label']} | `{variant_id}` | {variant.get('role', '—')} | `{source.get('relative_path', variant.get('kind'))}` | "
                        f"{(source.get('sha256') or source.get('content_hash') or '—')[:12]} | {variant['license']['id']} | {source.get('validator', {}).get('status', '—')} | "
                        f"{geometry} | {', '.join(variant.get('view_types', []))} | {variant.get('labelled_structures', 0)} | "
                        f"{variant['registration']['status']} | {result} |")
            summary.append({"system": system["id"], "variant": variant_id, "role": variant.get("role"), "kind": variant.get("kind"),
                            "source": source.get("relative_path"), "source_sha256": source.get("sha256"), "license": variant["license"]["id"],
                            "validator": source.get("validator", {}).get("status"), "triangles": stats.get("triangles"), "points": stats.get("points"),
                            "view_types": variant.get("view_types"), "standard_tier": {k: tier.get(k) for k in ("url", "bytes", "sha256", "triangles")},
                            "registration": variant["registration"]["status"], "browser": browser and {k: browser.get(k) for k in ("rendered", "draw_calls", "triangles", "points", "seconds")}})

    section = walk["sections"]["anatomy"]
    header = [
        "# Anatomy asset QA",
        "",
        f"Generated by `scripts/anatomy_asset_qa.py` from `public/anatomy/manifest.json` ({manifest['totals']['variants']} variants, "
        f"{manifest['totals']['systems']} systems) and the browser walkthrough of {walk['started_at'][:10]} ({walk['browser']}).",
        "",
        f"Browser result: **{section['variants_rendered']} of {section['variants_total']} variants rendered** in "
        f"{section['systems_with_all_variants_rendered']} of {section['systems_total']} systems with every variant rendered; "
        f"{len(walk['console_errors'])} console errors, {len(walk['page_errors'])} page errors, {len(walk['failed_requests'])} failed (5xx) requests.",
        "",
        "Render proof per variant = the viewer's own WebGL counters (draw calls and triangles or points from `renderer.info`, shown by the "
        "performance probe) **and** canvas pixel statistics (luminance standard deviation σ > 3 and > 1 % non-background pixels). "
        "A network 200 alone is not counted. The standard tier is what the browser loads; originals stay unmodified in the repository.",
        "",
        "View types are those the asset genuinely supports (an exterior shell clipped by a section plane is not called an interior). "
        "Every variant is `NOT_PATIENT_REGISTERED` (L1 generic reference); the hybrid system's layer registration states are listed in "
        "`public/anatomy/manifest.json` (`SOURCE_FRAME_SHARED`, `BBOX_TRANSLATION_ALIGNED`, `UNREGISTERED_BBOX_SCALED`) and pinned by "
        "`test_regression_contracts.py::test_hybrid_atlas_layers_never_claim_patient_registration`.",
        "",
        "| System | Variant | Role | Source | SHA-256 | Licence | glTF validator | Source geometry | View types | Labelled structures | Registration | Browser |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    out = ROOT / "docs" / "anatomy" / "ASSET_QA.md"
    out.write_text("\n".join(header + rows) + "\n", encoding="utf-8")
    pointer = ROOT / "assets" / "anatomy" / "asset_manifest.json"
    pointer.parent.mkdir(parents=True, exist_ok=True)
    pointer.write_text(json.dumps({
        "canonical_manifest": "public/anatomy/manifest.json",
        "note": "Redirect: the anatomy pipeline (tools/asset-pipeline) writes the canonical manifest under public/anatomy; this file summarises it with browser results.",
        "generated_from_walkthrough": walk["started_at"], "variants": summary,
    }, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} and {pointer.relative_to(ROOT)} ({len(rows)} variants)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
