<#
Move fully verified redundant source archives off D: into a recoverable folder.
Default is a read-only plan. Never removes datasets or performs permanent deletion.
The evidence report is generated by the archive audit, with one complete CRC check
for every retained extracted file. A separate generated ledger records each move.
#>
[CmdletBinding()]
param([switch]$Apply, [switch]$Named)

$ErrorActionPreference = 'Stop'
$projectRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path.TrimEnd('\')
$recoveryRoot = 'C:\Users\johnn\AppData\Local\Temp\medtwin-storage-recovery-20261027\archives'
$reportName = if ($Named) { 'named-archive-verification.json' } else { 'archive-verification.json' }
$reportPath = Join-Path $projectRoot (Join-Path '_imports\storage-cleanup-20261027' $reportName)
$ledgerPath = Join-Path $projectRoot '_imports\storage-cleanup-20261027\archive-moves.json'
$report = Get-Content -Raw -LiteralPath $reportPath | ConvertFrom-Json
if ($report.status -ne 'COMPLETE') { throw 'The archive audit must be complete first.' }
$records = New-Object 'System.Collections.Generic.List[object]'
function Add-LedgerRecords($value) {
    if ($null -eq $value) { throw 'The recovery ledger contains an empty entry.' }
    if ($value -is [Array]) {
        foreach ($item in $value) { Add-LedgerRecords $item }
        return
    }
    # Older Windows PowerShell serialization can wrap an array as {value,Count}.
    if ($value.PSObject.Properties['value'] -and $value.PSObject.Properties['Count'] -and
        @($value.PSObject.Properties).Count -eq 2) {
        Add-LedgerRecords $value.value
        return
    }
    if (-not $value.source -or -not $value.destination -or -not $value.sha256) {
        throw 'The recovery ledger contains a malformed entry.'
    }
    $records.Add($value)
}
if (Test-Path -LiteralPath $ledgerPath) {
    $parsedRecords = Get-Content -Raw -LiteralPath $ledgerPath | ConvertFrom-Json
    Add-LedgerRecords $parsedRecords
}

foreach ($entry in $report.archives) {
    if (-not $entry.redundant_archive -or $entry.mismatch_count -ne 0 -or
        $entry.verification -ne 'ALL_EXTRACTED_BYTES_AND_CRC32_MATCH' -or
        $entry.verified_files -ne $entry.zip_entries) { continue }
    $source = [IO.Path]::GetFullPath($entry.path)
    # Only individual top-level ZIPs in this exact project are in scope.
    if ([IO.Path]::GetDirectoryName($source) -ne $projectRoot -or
        [IO.Path]::GetExtension($source) -ne '.zip') { throw "Out-of-scope source: $source" }
    $destination = Join-Path $recoveryRoot ([IO.Path]::GetFileName($source))
    if (-not (Test-Path -LiteralPath $source)) { continue }
    $file = Get-Item -LiteralPath $source
    if ($file.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw "Reparse point: $source" }
    if ($file.Length -ne $entry.archive_bytes) { throw "Archive changed: $source" }
    if (Test-Path -LiteralPath $destination) { throw "Destination already exists: $destination" }
    if (-not $Apply) {
        [pscustomobject]@{ Source=$source; Destination=$destination; Bytes=$file.Length }
        continue
    }
    # Leave at least 20 GiB on C:, even if other applications consume space.
    if ((Get-PSDrive -Name C).Free - $file.Length -lt 20GB) {
        Write-Warning "Recovery capacity limit reached; keeping $source on D:."
        break
    }
    $null = New-Item -ItemType Directory -Path $recoveryRoot -Force
    if ((Resolve-Path -LiteralPath $recoveryRoot).Path -ne $recoveryRoot) { throw 'Unexpected recovery root.' }
    $sourceHash = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash
    Move-Item -LiteralPath $source -Destination $destination -ErrorAction Stop
    $destinationHash = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash
    if ($sourceHash -ne $destinationHash) { throw "Recovery hash mismatch: $destination" }
    $records.Add([pscustomobject]@{
        moved_at_utc=[DateTime]::UtcNow.ToString('o'); source=$source; destination=$destination
        bytes=$file.Length; sha256=$sourceHash; retained_file_manifest=$entry.manifest
        recovery='Move destination back to source to restore the original archive location.'
    })
    # This is generated operation evidence, not source configuration.
    ConvertTo-Json -InputObject $records.ToArray() -Depth 5 | Set-Content -LiteralPath $ledgerPath -Encoding UTF8
    Write-Output ("Recovered {0:N2} GiB from D: by moving {1}" -f ($file.Length / 1GB), $file.Name)
}
